import { Injectable, Logger } from '@nestjs/common';
import { PrismaService } from '../../../prisma/prisma.service';
import { createHash } from 'crypto';

@Injectable()
export class TourKnowledgeIngestionService {
  private readonly logger = new Logger(TourKnowledgeIngestionService.name);

  constructor(private readonly prisma: PrismaService) {}

  /**
   * Generates SHA-256 content hash for drift detection
   */
  private generateContentHash(content: string): string {
    return createHash('sha256').update(content).digest('hex');
  }

  /**
   * Sync active database Tours and TourLandingPages into KnowledgeBaseItem records
   * for RAG retrieval grounding.
   */
  async syncCatalogToKnowledgeBase(): Promise<{ syncedTours: number; syncedDestinations: number }> {
    this.logger.log('Starting Tour Catalog to Knowledge Base ingestion sync...');

    let syncedTours = 0;
    let syncedDestinations = 0;

    // 1. Fetch active published tours
    const tours = await this.prisma.tour.findMany({
      where: {
        isActive: true,
        status: 'PUBLISHED',
        deletedAt: null,
      },
      take: 100,
    });

    for (const tour of tours) {
      const tourAny = tour as any;
      const sourceKey = `CATALOG_TOUR:${tour.id}`;
      let title = tour.slug;
      if (tour.titleJsonb && typeof tour.titleJsonb === 'object') {
        const tMap = tour.titleJsonb as Record<string, string>;
        title = tMap.en || tMap.ar || title;
      }

      const destinationStr = [tour.city, tour.country].filter(Boolean).join(', ') || 'Egypt & Middle East';
      const durationVal = tourAny.durationDays || tourAny.duration;
      const durationStr = durationVal ? `${durationVal} Days` : 'Multi-day';
      const priceStr = tour.basePriceUsd ? `$${tour.basePriceUsd} ${tour.currency || 'USD'}` : 'On Request';
      const content = `Tour Package: ${title}\nDestination: ${destinationStr}\nDuration: ${durationStr}\nStarting Price: ${priceStr}\nCategory: ${tour.category || 'Luxury'}\nPublic URL: /tours/${tour.slug}`;
      const contentHash = this.generateContentHash(content);

      const existing = await (this.prisma as any).knowledgeBaseItem.findFirst({
        where: {
          sourceEntityType: 'TOUR',
          sourceEntityId: tour.id,
        },
      });

      if (existing) {
        // Respect manual overrides!
        if (!existing.isManuallyOverridden) {
          await (this.prisma as any).knowledgeBaseItem.update({
            where: { id: existing.id },
            data: {
              title: `[Catalog Tour] ${title}`,
              content,
              contentHash,
              locale: 'en',
              category: 'CUSTOM_TOURS',
              tags: [tour.slug, destinationStr.toLowerCase(), 'tour', 'package'],
              status: 'PUBLISHED',
              priority: 15,
              syncStatus: 'SYNCED',
              lastIndexedAt: new Date(),
              lastSyncedAt: new Date(),
            },
          });
        }
      } else {
        await (this.prisma as any).knowledgeBaseItem.create({
          data: {
            title: `[Catalog Tour] ${title}`,
            content,
            contentHash,
            locale: 'en',
            category: 'CUSTOM_TOURS',
            tags: [tour.slug, destinationStr.toLowerCase(), 'tour', 'package'],
            status: 'PUBLISHED',
            source: sourceKey,
            sourceType: 'TOUR',
            sourceEntityType: 'TOUR',
            sourceEntityId: tour.id,
            isAutoGenerated: true,
            isManuallyOverridden: false,
            isExcludedFromAi: false,
            priority: 15,
            syncStatus: 'SYNCED',
            lastIndexedAt: new Date(),
            lastSyncedAt: new Date(),
          },
        });
      }
      syncedTours++;
    }

    // 2. Fetch active tour landing pages (destinations)
    const landingPages = await (this.prisma as any).tourLandingPage.findMany({
      where: {
        isActive: true,
        status: 'PUBLISHED',
        deletedAt: null,
      },
      take: 50,
    }).catch(() => []);

    for (const lp of landingPages) {
      const sourceKey = `CATALOG_DESTINATION:${lp.id}`;
      let title = lp.slug.toUpperCase();
      if (lp.titleJsonb && typeof lp.titleJsonb === 'object') {
        const tMap = lp.titleJsonb as Record<string, string>;
        title = tMap.en || tMap.ar || title;
      }

      const content = `Destination Guide: ${title}\nSlug: ${lp.slug}\nType: ${lp.type || 'Destination'}\nPublic URL: /destinations/${lp.slug}`;
      const contentHash = this.generateContentHash(content);

      const existing = await (this.prisma as any).knowledgeBaseItem.findFirst({
        where: {
          sourceEntityType: 'TOUR_LANDING_PAGE',
          sourceEntityId: lp.id,
        },
      });

      if (existing) {
        if (!existing.isManuallyOverridden) {
          await (this.prisma as any).knowledgeBaseItem.update({
            where: { id: existing.id },
            data: {
              title: `[Destination Guide] ${title}`,
              content,
              contentHash,
              locale: 'en',
              category: 'DESTINATION_INFO',
              tags: [lp.slug, 'destination', 'guide'],
              status: 'PUBLISHED',
              priority: 12,
              syncStatus: 'SYNCED',
              lastIndexedAt: new Date(),
              lastSyncedAt: new Date(),
            },
          });
        }
      } else {
        await (this.prisma as any).knowledgeBaseItem.create({
          data: {
            title: `[Destination Guide] ${title}`,
            content,
            contentHash,
            locale: 'en',
            category: 'DESTINATION_INFO',
            tags: [lp.slug, 'destination', 'guide'],
            status: 'PUBLISHED',
            source: sourceKey,
            sourceType: 'DESTINATION',
            sourceEntityType: 'TOUR_LANDING_PAGE',
            sourceEntityId: lp.id,
            isAutoGenerated: true,
            isManuallyOverridden: false,
            isExcludedFromAi: false,
            priority: 12,
            syncStatus: 'SYNCED',
            lastIndexedAt: new Date(),
            lastSyncedAt: new Date(),
          },
        });
      }
      syncedDestinations++;
    }

    this.logger.log(`Knowledge Base ingestion sync complete! Ingested ${syncedTours} tours and ${syncedDestinations} destinations.`);
    return { syncedTours, syncedDestinations };
  }
}
